def _order(Order, Rung, order_id, org_id, rungs, *, tip="0", lottery=0, hours="1"):
    return {
        "order_id": order_id,
        "org_id": org_id,
        "lottery": lottery,
        "tip": tip,
        "hours": hours,
        "rungs": [{"pool_id": pool, "max": price} for pool, price in rungs],
    }


def _sim_order(Order, Rung, spec, *, kind="realtime"):
    return Order(
        spec["order_id"],
        spec["org_id"],
        tuple(Rung(rung["pool_id"], max_price=float(rung["max"]), willingness=float(rung["max"])) for rung in spec["rungs"]),
        quantity=float(spec["hours"]),
        tip=float(spec["tip"]),
        lottery=spec["lottery"],
        kind=kind,
    )


def _sim_pools(PoolView, pools):
    return {
        pool["pool_id"]: PoolView(
            pool["pool_id"],
            supply=float(pool["supply"]),
            base=float(pool["base"]),
            reserve=float(pool["reserve"]),
        )
        for pool in pools
    }


def _engine_pool(pool_id, *, supply, base, reserve, trail):
    return {
        "pool_id": pool_id,
        "class_id": "class",
        "region": "lab",
        "supply_hours": supply,
        "n_hosts": 8,
        "reserve_cents": reserve,
        "prev_base_cents": base,
        "trailing_util_24h": trail,
        "boost": {"applied": "1.3", "direction": 0, "prev_trail": None},
    }


def _engine_order(order_id, org_id, rungs, *, tip=0, lottery=0, hours="1"):
    return {
        "order_id": order_id,
        "org_id": org_id,
        "lottery": lottery,
        "tip_cents": tip,
        "hours": hours,
        "rungs": [{"pool_id": pool, "max_cents": cents} for pool, cents in rungs],
    }


def _clearing(result) -> dict:
    return {
        "passes": result.passes,
        "scarce": {pool_id: pool.scarce for pool_id, pool in sorted(result.pools.items())},
        "fills": _fills(result),
    }


def _fills(result) -> list[dict]:
    return [
        {
            "order_id": fill.order_id,
            "org_id": fill.org_id,
            "pool_id": fill.pool_id,
            "rung_index": fill.rung_index,
            "hours": _num(fill.quantity),
            "pay": _num(fill.pay_per_hour),
        }
        for fill in result.fills
    ]


def _doc(cases) -> dict:
    return {"simulated": True, "note": NOTE, "cases": cases}


def _num(value: float) -> str:
    return format(value, ".17g")


def _write(name: str, payload: dict) -> None:
    path = FIXTURES / name
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
